// Emits dist/_headers, the response headers Cloudflare applies to every static
// asset it serves. Generated rather than hand-written for one reason: the
// Content-Security-Policy has to name a hash for the pre-paint theme script in
// index.html, and a hash maintained by hand goes stale the first time that
// script is edited. The failure would be silent in review and visible only as a
// blocked script in production, so the hash is computed from the built HTML on
// every build.
//
// Worker responses are not covered here. Cloudflare applies this file to asset
// responses only, so /api/* carries its own headers from worker/index.js.

import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { SIMPLE_ANALYTICS_ENDPOINT } from './src/observability/simple-analytics.js'

// Scripts with a src attribute load from the site itself and are covered by
// 'self'; only inline bodies need a hash.
const INLINE_SCRIPT = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi

export function inlineScriptHashes(html) {
  const hashes = []
  for (const [, body] of html.matchAll(INLINE_SCRIPT)) {
    if (!body.trim()) continue
    hashes.push(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`)
  }
  return [...new Set(hashes)]
}

// A DSN carries credentials in the userinfo position; origin drops them.
export function providerOrigin(url) {
  try {
    return new URL(url).origin
  } catch {
    return ''
  }
}

export function contentSecurityPolicy({ scriptHashes = [], browserDsn = '' } = {}) {
  // Derived from the module that actually sends the telemetry rather than
  // repeated here, so a changed endpoint cannot be silently refused by a policy
  // still naming the old one.
  const connect = ["'self'", providerOrigin(SIMPLE_ANALYTICS_ENDPOINT), providerOrigin(browserDsn)]

  return [
    "default-src 'self'",
    ["script-src 'self'", ...scriptHashes].join(' '),
    // Authored pages carry style attributes and the app sets inline styles, so
    // styles cannot be hashed the way the one inline script can. Scripts keep a
    // strict policy regardless: naming a hash makes a browser ignore
    // 'unsafe-inline' for script-src even if one is ever added by accident.
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
    "font-src 'self' https://fonts.gstatic.com",
    // data: covers the grain texture and any asset Vite inlines under its size
    // threshold.
    "img-src 'self' data:",
    "media-src 'self'",
    ['connect-src', ...new Set(connect.filter(Boolean))].join(' '),
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "object-src 'none'",
  ].join('; ')
}

export function securityHeadersFile(policy) {
  return [
    '# Generated by vite-security-headers.js on build — do not edit.',
    '/*',
    `  Content-Security-Policy: ${policy}`,
    // The site forwards no referrers of its own, matching the analytics
    // envelopes and the observability runbook's allowlist.
    '  Referrer-Policy: no-referrer',
    '  Strict-Transport-Security: max-age=31536000',
    '  X-Content-Type-Options: nosniff',
    '  X-Frame-Options: DENY',
    '  Cross-Origin-Opener-Policy: same-origin',
    '  Permissions-Policy: accelerometer=(), camera=(), display-capture=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()',
    '',
  ].join('\n')
}

export function securityHeaders({ browserDsn = '' } = {}) {
  return {
    name: 'security-headers',
    apply: 'build',
    async writeBundle(options) {
      const outputDirectory = options.dir ?? 'dist'
      const html = await readFile(join(outputDirectory, 'index.html'), 'utf8')
      const scriptHashes = inlineScriptHashes(html)
      if (scriptHashes.length === 0) {
        throw new Error('security-headers: no inline script found in the built index.html')
      }

      await writeFile(
        join(outputDirectory, '_headers'),
        securityHeadersFile(contentSecurityPolicy({ scriptHashes, browserDsn })),
      )
    },
  }
}
